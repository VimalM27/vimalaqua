// Quick lookup helpers
window.VPW_getProductBySlug = function(slug) {
  return window.VPW_PRODUCTS.find(function(p){ return p.slug === slug; });
};
window.VPW_getRelatedProducts = function(product, limit) {
  limit = limit || 4;
  if (!product) return [];
  return window.VPW_PRODUCTS
    .filter(function(p){ return p.category === product.category && p.slug !== product.slug; })
    .slice(0, limit);
};
