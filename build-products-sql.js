/* Builds supabase-products-seed.sql from js/products-data.js + js/product-meta.js.
   Uses the SAME merge rules as js/vpw-catalog.js (meta price overrides data price).
   Run from the project root:   node tools/build-products-sql.js
   Re-run it and paste the new SQL into Supabase whenever you change a price or stock. */
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
global.window = {};
new Function('window', fs.readFileSync(path.join(root, 'js/products-data.js'), 'utf8'))(global.window);
new Function('window', fs.readFileSync(path.join(root, 'js/product-meta.js'), 'utf8'))(global.window);
const P = window.VPW_PRODUCTS || [], M = window.VPW_META || {};

function stateOf(p, m) {               // same logic as vpw-catalog.js
  const a = m.availability ? String(m.availability).toLowerCase() : null;
  if (m.stock != null && m.stock !== '') return Number(m.stock) > 0 ? 'in_stock' : 'out_of_stock';
  if (a) { if (/^(in[_ ]?stock|available)$/.test(a)) return 'in_stock'; if (/out/.test(a)) return 'out_of_stock'; return 'contact'; }
  const base = String(p.availability || '').toLowerCase();
  if (/^available$/.test(base)) return 'in_stock';
  if (/out of stock|sold/.test(base)) return 'out_of_stock';
  return 'contact';
}
const q = s => "'" + String(s == null ? '' : s).replace(/'/g, "''") + "'";

const rows = [], skipped = [];
P.forEach(p => {
  const m = M[p.slug] || {};
  let price = p.price, onReq = !!p.priceOnRequest;
  if (m.price != null && m.price !== '') { price = Number(m.price); onReq = false; }
  if (m.priceOnRequest === true) onReq = true;
  price = onReq ? null : (price == null ? null : Number(price));
  if (price == null || !(price > 0)) { skipped.push(p.name + ' (price on request)'); return; }
  const active = stateOf(p, m) !== 'out_of_stock';
  rows.push(`  (${q(p.slug)}, ${q(p.name)}, ${q(p.category || 'Products')}, ${price.toFixed(2)}, ${p.type === 'pet'}, ${active})`);
});

const sql = `-- GENERATED by tools/build-products-sql.js. Do not edit by hand.
-- Safe to re-run: it updates existing rows and adds new ones.
insert into public.vp_products (slug, name, category, price, is_live, active) values
${rows.join(',\n')}
on conflict (slug) do update set
  name = excluded.name, category = excluded.category, price = excluded.price,
  is_live = excluded.is_live, active = excluded.active, updated_at = now();

-- Products that exist in the table but are no longer in the catalogue are switched off:
update public.vp_products set active = false, updated_at = now()
 where slug not in (${rows.map(r => r.match(/^\s*\('([^']*)'/)[1] && "'" + r.match(/^\s*\('((?:[^']|'')*)'/)[1] + "'").join(', ')});
`;
fs.writeFileSync(path.join(root, 'supabase-products-seed.sql'), sql);
console.log(`Wrote supabase-products-seed.sql: ${rows.length} orderable products.`);
if (skipped.length) console.log('Skipped (not orderable online):\n  - ' + skipped.join('\n  - '));
