/* Rebuilds js/search-index.js so site search knows every product on every page.
   Run from the project folder after you add or change products:   node tools/build-search-index.js */
const fs = require('fs'), path = require('path'), vm = require('vm');
const root = path.join(__dirname, '..');
const sandbox = { window: {} }; vm.createContext(sandbox);
['js/products-data.js', 'js/product-meta.js'].forEach(f => { try { vm.runInContext(fs.readFileSync(path.join(root, f), 'utf8'), sandbox); } catch (e) { console.warn('skip', f, e.message); } });
const PRODUCTS = sandbox.window.VPW_PRODUCTS || [], META = sandbox.window.VPW_META || {};
const slugify = s => String(s || '').trim().toLowerCase().replace(/[^a-z0-9\s-]/g, '').replace(/\s+/g, '-').replace(/-+/g, '-').replace(/^-|-$/g, '');
const clean = s => String(s || '').replace(/&amp;/g, '&').replace(/&#39;/g, "'").replace(/&quot;/g, '"').replace(/<[^>]*>/g, '').replace(/\s+/g, ' ').replace(/\s+[–—-]\s+/g, ' – ').trim();
const num = v => { const m = String(v == null ? '' : v).replace(/,/g, '').match(/\d+(\.\d+)?/); return m ? parseFloat(m[0]) : null; };
const items = [], seen = new Set();
PRODUCTS.forEach(p => {
  const m = META[p.slug] || {};
  let price = (m.price != null && m.price !== '') ? Number(m.price) : p.price;
  const onReq = m.priceOnRequest === true || (p.priceOnRequest && !(m.price != null && m.price !== ''));
  price = onReq ? null : num(price);
  let st = 'contact'; const a = String(m.availability || p.availability || '').toLowerCase();
  if (m.stock != null && m.stock !== '') st = Number(m.stock) > 0 ? 'in' : 'out';
  else if (/^(in[_ ]?stock|available)$/.test(a)) st = 'in'; else if (/out|sold/.test(a)) st = 'out';
  const k = [].concat(m.keywords || [], p.keywords || [], m.brand || '', p.type || '').filter(Boolean).join(' ');
  seen.add(slugify(p.name));
  items.push({ n: clean(p.name), c: p.category || '', u: 'product.html?id=' + encodeURIComponent(p.slug), i: (p.images && p.images[0]) || '', p: price, s: st, k: k.toLowerCase(), l: 1 });
});
/* cards that only exist on a page (toys, aquarium extras...) */
const pageLabel = html => { const h = (html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/i) || [])[1]; const t = (html.match(/<title>([\s\S]*?)<\/title>/i) || [])[1] || ''; return clean(h || t.split('|')[0].split(' - ')[0]); };
fs.readdirSync(root).filter(f => f.endsWith('.html') && !['search-results.html', 'product.html', 'cart.html', 'wishlist.html'].includes(f)).forEach(f => {
  const html = fs.readFileSync(path.join(root, f), 'utf8'); const label = pageLabel(html);
  const re = /<div class="product-card"[^>]*>([\s\S]*?)<\/div>\s*(?=<div class="product-card"|<\/section>|<\/div>\s*<\/section>|\n\s*\n)/g; let m;
  const blocks = html.split(/<div class="product-card"/).slice(1);
  blocks.forEach(b => {
    const h = (b.match(/<h[234][^>]*>([\s\S]*?)<\/h[234]>/i) || [])[1]; if (!h) return;
    const name = clean(h), slug = slugify(name); if (!slug || seen.has(slug)) return; seen.add(slug);
    const img = (b.match(/<img[^>]*src="([^"]+)"/i) || [])[1] || '';
    const pr = (b.match(/class="price"[^>]*>([\s\S]*?)<\/p>/i) || [])[1];
    const d = (b.match(/class="description"[^>]*>([\s\S]*?)<\/p>/i) || [])[1];
    items.push({ n: name, c: label, u: f, i: img, p: pr ? num(clean(pr)) : null, s: 'contact', k: clean(d || '').toLowerCase().slice(0, 120), l: 0 });
  });
});
fs.writeFileSync(path.join(root, 'js/search-index.js'), '/* AUTO-GENERATED by tools/build-search-index.js. Do not edit by hand. */\nwindow.VP_SEARCH_INDEX=' + JSON.stringify(items) + ';\n');
console.log('indexed', items.length, 'items (' + items.filter(x => x.l).length + ' catalogue + ' + items.filter(x => !x.l).length + ' page-only)');
